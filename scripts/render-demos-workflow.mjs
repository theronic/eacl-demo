import { access, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

import { assertOrdinaryDemoWorkflowPolicy } from "../packages/qualification/src/workflow-policy.mjs";
import { assertLiveOrdinaryTargetPairs, eligibleOrdinaryTargets, renderOrdinaryWorkflow } from "./lib/ordinary-workflow.mjs";

const root = path.resolve(import.meta.dirname, "..");
const workflowPath = path.join(root, ".github", "workflows", "deploy-demos.yml");
const buildUnits = JSON.parse(await readFile(path.join(root, "build-units.json"), "utf8"));
const profileDefinitions = JSON.parse(await readFile(path.join(root, "packages", "contracts", "profiles.v1.json"), "utf8"));
const eligible = eligibleOrdinaryTargets(buildUnits);
const deployEntrypointAvailable = await exists(path.join(root, "scripts", "deploy-ordinary-target.mjs"));
const expected = renderOrdinaryWorkflow(buildUnits, { deployEntrypointAvailable });
const mode = process.argv[2] ?? "--check";

if (mode === "--check") {
  const actual = await readFile(workflowPath, "utf8").catch((error) => error.code === "ENOENT" ? null : Promise.reject(error));
  if (actual !== null && !actual.startsWith("# Generated by scripts/render-demos-workflow.mjs.")) {
    assertOrdinaryDemoWorkflowPolicy(actual);
    const liveTargets = assertLiveOrdinaryTargetPairs(actual, profileDefinitions);
    process.stdout.write(`live ordinary workflow policy current (${liveTargets.join(", ")})\n`);
    process.exit(0);
  }
  if (expected === null && actual !== null) throw new Error("automatic demos workflow must be absent while no ordinary target is eligible");
  if (expected !== null && actual !== expected) throw new Error("automatic demos workflow is missing or stale for the eligible target set");
  process.stdout.write(expected === null ? "automatic demos workflow correctly absent (zero eligible targets)\n" : `automatic demos workflow current (${eligible.join(", ")})\n`);
} else if (mode === "--write") {
  if (expected === null) throw new Error("refusing to create an automatic demos workflow while zero ordinary targets are eligible");
  const current = await readFile(workflowPath, "utf8").catch((error) => error.code === "ENOENT" ? null : Promise.reject(error));
  if (current !== null && !current.startsWith("# Generated by scripts/render-demos-workflow.mjs.")) throw new Error("refusing to overwrite a non-generated workflow");
  await writeFile(workflowPath, expected);
  process.stdout.write(`${path.relative(root, workflowPath)}\t${eligible.join(",")}\n`);
} else throw new Error("usage: node scripts/render-demos-workflow.mjs [--check|--write]");

async function exists(file) {
  return access(file).then(() => true, () => false);
}
