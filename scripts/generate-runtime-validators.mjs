import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";

const root = new URL("../", import.meta.url);
const outputUrl = new URL("packages/contracts/src/generated/runtime-validators.mjs", root);
const schemaNames = [
  "artifact-digests.v1",
  "error-codes.v1",
  "explorer.v1",
  "explorer-client-request.v1",
  "explorer-response.v1",
  "explorer-worker-message.v1",
  "explorer-worker-event.v1",
  "explorer-descriptor.v1",
  "fixture-manifest-boundary.v1",
  "profile-registry.v1",
  "profile-publication.v1",
  "benchmark-evidence-index.v1",
  "fastest-storage-evidence.v1",
  "release-manifest.v1"
];

const validatorIds = Object.freeze({
  client: "https://demo.eacl.dev/schemas/explorer-client-request.v1.schema.json",
  server: "https://demo.eacl.dev/schemas/explorer-response.v1.schema.json",
  worker: "https://demo.eacl.dev/schemas/explorer-worker-message.v1.schema.json",
  workerEvent: "https://demo.eacl.dev/schemas/explorer-worker-event.v1.schema.json",
  fixture: "https://demo.eacl.dev/schemas/fixture-manifest-boundary.v1.schema.json",
  descriptor: "https://demo.eacl.dev/schemas/explorer-descriptor.v1.schema.json",
  registry: "https://demo.eacl.dev/schemas/profile-registry.v1.schema.json",
  profilePublication: "https://demo.eacl.dev/schemas/profile-publication.v1.schema.json",
  benchmarkIndex: "https://demo.eacl.dev/schemas/benchmark-evidence-index.v1.schema.json",
  fastestEvidence: "https://demo.eacl.dev/schemas/fastest-storage-evidence.v1.schema.json",
  release: "https://demo.eacl.dev/schemas/release-manifest.v1.schema.json"
});

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  validateFormats: true,
  allowUnionTypes: true,
  code: { source: true, esm: true, lines: true }
});
addFormats(ajv);
for (const name of schemaNames) {
  const schema = JSON.parse(await readFile(new URL(`schemas/${name}.schema.json`, root), "utf8"));
  ajv.addSchema(schema);
}

let generated = standaloneCode(ajv, validatorIds);
generated = generated
  .replace('const func1 = require("ajv/dist/runtime/ucs2length").default;', 'const func1 = ucs2lengthRuntime.default;')
  .replace('const formats0 = require("ajv-formats/dist/formats").fullFormats["date-time"];', 'const formats0 = formatsRuntime.fullFormats["date-time"];')
  .replace('const func0 = require("ajv/dist/runtime/equal").default;', 'const func0 = equalRuntime.default;');
assert.equal(generated.includes("require("), false, "standalone validators contain an unsupported CommonJS runtime import");

const source = [
  "// Generated by scripts/generate-runtime-validators.mjs. Do not edit.",
  'import ucs2lengthRuntime from "ajv/dist/runtime/ucs2length.js";',
  'import equalRuntime from "ajv/dist/runtime/equal.js";',
  'import formatsRuntime from "ajv-formats/dist/formats.js";',
  "",
  generated,
  ""
].join("\n");

if (process.argv.includes("--check")) {
  const existing = await readFile(outputUrl, "utf8").catch(() => null);
  assert.equal(existing, source, "runtime validators are stale; run npm run generate:runtime-validators");
} else {
  await mkdir(new URL(".", outputUrl), { recursive: true });
  await writeFile(outputUrl, source);
  console.log(`runtime-validators\t${Object.keys(validatorIds).length} validators\t${Buffer.byteLength(source)} bytes`);
}
